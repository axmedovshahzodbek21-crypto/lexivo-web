// Case catalogue and sentence bank for the rule-based weekly class digest
// (lib/class-digest.ts). Same idea as the per-student summary
// (lib/student-summary-sentences.ts).
//
// Definitions every rule below uses:
//   week        the last 7 full days, ending yesterday; "last week" = the 7 before.
//   total       approved members who joined before the week ended.
//   active      a student with at least one class XP entry in the week.
//   on-time %   (student × homework pairs fully done by the due date) / (pairs due
//               in the week). Every mode counts; partly done = missed
//               (lib/homework-deadlines.ts).
//   waiting     class_srs_states with stage < 5 and next_due <= today.
//   overdue     waiting and next_due < today.
//   accuracy    knew / all answers in class_review_events.
// Learn speed and Learn gate accuracy are deliberately NOT used: on real data
// fast words were all correct and 97% of words pass the gate first try.
//
// Sentence rules: say what happened, never judge it; pair a concern with what the
// student does do; a suggestion is help, not pressure. No suffixes on {name},
// {names}, {hw}, {word}, {words} — they don't always take one cleanly.
//
// [[label|key]] is a tappable phrase that opens the facts behind the claim.
// Keys: students weeks days homework review accuracy words notes.
//
// Ready-made counted nouns, filled by the engine so English singular/plural is
// right: {students} {tasks} {wordCount} {dayCount}. English agreement for the
// case's subject: {were} (was/were), {have} (has/have).

